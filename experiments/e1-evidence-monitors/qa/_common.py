def _norm_bool(v):
    if isinstance(v, bool) or v is None:
        return v
    if isinstance(v, (int, float)):
        return bool(v)
    if isinstance(v, str):
        s = v.strip().lower()
        if s in {"violation", "true", "harmful", "1", "yes"}:
            return True
        if s in {"compliant", "false", "benign", "0", "no"}:
            return False
    if isinstance(v, dict):
        for k in ("violation", "label", "value"):
            if k in v:
                return _norm_bool(v[k])
    return None


def _builder_labels(row: dict) -> dict:
    """Extract every label-like VALUE from a manifest row (never calls label code)."""
    out = {}
    for k, v in row.items():
        lk = k.lower()
        if lk in {"label", "labels", "label_sql", "label_replay", "sql", "replay", "violation", "c_full",
                  "label_value", "temporal_label"} or lk.startswith("label"):
            if isinstance(v, dict) and not any(x in v for x in ("violation", "label", "value")):
                for k2, v2 in v.items():
                    b = _norm_bool(v2)
                    if b is not None:
                        out[f"{k}.{k2}"] = b
            else:
                b = _norm_bool(v)
                if b is not None:
                    out[k] = b
    return out


def discover_spike_worlds() -> list[dict]:
    out = []
    for idx in sorted(glob.glob(str(E1 / "runs" / "*" / "private" / "world_index.json"))):
        run = Path(idx).parents[1]
        rows_ = json.loads(Path(idx).read_text())
        meta = json.loads((run / "run_meta.json").read_text()) if (run / "run_meta.json").exists() else {}
        dc = {}
        if (run / "deterministic_checks.json").exists():
            d = json.loads((run / "deterministic_checks.json").read_text())
            for r in d.get("labels", {}).get("rows", []):
                dc[r["pid"]] = {"label_sql": r.get("sql"), "label_replay": r.get("replay")}
        for r in rows_:
            db = run / "worlds" / f"{r['pid']}.sqlite"
            if not db.exists():
                continue
            out.append({"source": f"spike:{run.name}", "pid": r["pid"], "db": db, "family": "F1",
                        "variant": r.get("variant"), "split": "spike", "base_case": f"{run.name}:{r['case']}",
                        "harmful": r.get("harmful"), "seed": r.get("seed"),
                        "generator_version": meta.get("generator_version", "f1-v1"),
                        "builder_labels": {k: v for k, v in dc.get(r["pid"], {}).items() if v is not None}})
    return out


def _manifest_rows(path: Path):
    try:
        if path.suffix == ".jsonl":
            for ln in path.read_text(encoding="utf-8").splitlines():
                ln = ln.strip()
                if ln:
                    yield json.loads(ln)
        else:
            d = json.loads(path.read_text(encoding="utf-8"))
            if isinstance(d, list):
                yield from d
            elif isinstance(d, dict):
                for k in ("worlds", "rows", "cases", "items"):
                    if isinstance(d.get(k), list):
                        for r in d[k]:
                            if isinstance(r, dict):
                                r = dict(r)
                                r.setdefault("_manifest_meta", {kk: vv for kk, vv in d.items()
                                                                if not isinstance(vv, list)})
                            yield r
                        break
    except Exception as e:  # noqa: BLE001
        print(f"[qa] could not parse manifest {path}: {e}", file=sys.stderr)


def _resolve_db(row: dict, manifest: Path) -> Path | None:
    for k in ("db_path", "db", "world_db", "sqlite", "path"):
        v = row.get(k)
        if isinstance(v, str) and v.endswith((".sqlite", ".db", ".sqlite3")):
            for base in (manifest.parent, EXP, E1, Path(".")):
                p = (base / v)
                if p.exists():
                    return p.resolve()
            if Path(v).exists():
                return Path(v).resolve()
    pid = row.get("pid") or row.get("world_id") or row.get("private_id")
    if pid:
        hits = glob.glob(str(manifest.parent / "**" / f"{pid}.sqlite"), recursive=True)
        if hits:
            return Path(hits[0]).resolve()
    return None


def discover_case_worlds(include_f4=True) -> list[dict]:
    """Builder layout (families/make_cases.py): cases/private/world_index.json (F1-F3, with designed `harmful` and
    any label values the builder chooses to add), cases/worlds/<wid>.sqlite|.json; F4 sealed in cases/f4_sealed/
    with sealed_key.json (+ seeds in cases/f4_manifest.json). F4 rows carry sealed=True: QA reports counts only."""
    out = []
    # builder label VALUES (qa/REQUESTS.md R1): cases/private/qa_manifest.json, rows keyed by pid
    qam = E1 / "cases" / "private" / "qa_manifest.json"
    bl = {}
    if qam.exists():
        try:
            for r in json.loads(qam.read_text(encoding="utf-8")).get("rows", []):
                bl[r["pid"]] = {k: r[k] for k in ("label_sql", "label_replay") if k in r and r[k] is not None}
        except Exception as e:  # noqa: BLE001
            print(f"[qa] could not read qa_manifest: {e}", file=sys.stderr)
    idx = E1 / "cases" / "private" / "world_index.json"
    man = E1 / "cases" / "split_manifest.json"
    gv = None
    if man.exists():
        try:
            gv = json.loads(man.read_text(encoding="utf-8")).get("generator_version")
        except Exception:  # noqa: BLE001
            pass
    if idx.exists():
        for r in json.loads(idx.read_text(encoding="utf-8")):
            db = E1 / "cases" / "worlds" / f"{r['wid']}.sqlite"
            if not db.exists():
                continue
            out.append({"source": "cases", "pid": r["wid"], "db": db, "family": r.get("family"),
                        "variant": r.get("template"), "split": r.get("split"), "base_case": r.get("case_id"),
                        "harmful": _norm_bool(r.get("harmful")), "seed": r.get("seed"),
                        "generator_version": r.get("generator_version", gv),
                        "builder_labels": {**_builder_labels(r), **bl.get(r["wid"], {})}, "sealed": False})
    key = E1 / "cases" / "f4_sealed" / "sealed_key.json"
    f4m = E1 / "cases" / "f4_manifest.json"
    if include_f4 and key.exists():
        seeds = {}
        if f4m.exists():
            for c in json.loads(f4m.read_text(encoding="utf-8")).get("cases", []):
                seeds[c["case_id"]] = c.get("seed")
        for r in json.loads(key.read_text(encoding="utf-8")):
            db = E1 / "cases" / "f4_sealed" / f"{r['wid']}.sqlite"
            if not db.exists():
                continue
            out.append({"source": "cases", "pid": r["wid"], "db": db, "family": "F4", "variant": r.get("template"),
                        "split": "f4_reserved", "base_case": r.get("case_id"), "harmful": _norm_bool(r.get("harmful")),
                        "seed": seeds.get(r.get("case_id")), "generator_version": gv,
                        "builder_labels": {**_builder_labels(r), **bl.get(r["wid"], {})}, "sealed": True})
    return out


def discover_qa_local_worlds() -> list[dict]:
    idx = QA_LOCAL / "index.json"
    if not idx.exists():
        return []
    out = []
    for r in json.loads(idx.read_text()):
        r = dict(r)
        r["db"] = QA_LOCAL / r["db"]
        r["source"] = "qa_local"
        r.setdefault("builder_labels", {})
        out.append(r)
    return out


def discover_all(include_qa_local=True, include_f4=True) -> list[dict]:
    w = discover_case_worlds(include_f4) + discover_spike_worlds()
    if include_qa_local:
        w += discover_qa_local_worlds()
    return w


def cases_fingerprint() -> dict:
    """Fingerprint of everything QA consumes, so QA_REPORT can say which generation it covers."""
    files = [str(p) for p in (E1 / "cases" / "split_manifest.json", E1 / "cases" / "private" / "world_index.json",
                              E1 / "cases" / "private" / "qa_manifest.json", E1 / "cases" / "f4_manifest.json") if p.exists()]
    gens = sorted(glob.glob(str(E1 / "families" / "*.py")) + glob.glob(str(E1 / "env" / "workflowlab.py"))
                  + glob.glob(str(E1 / "env" / "render.py"))
                  + [str(E1 / "monitors" / f) for f in ("prompts.py", "policies.py", "query_api.py", "worlds.py", "handbook.py", "harness.py")
                     if (E1 / "monitors" / f).exists()])
    return {"manifests": {Path(f).relative_to(E1).as_posix(): file_sha(Path(f))[:12] for f in files},
            "generator_files": {Path(f).relative_to(E1).as_posix(): file_sha(Path(f))[:12] for f in gens}}
