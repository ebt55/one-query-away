"""Shared helpers for A3's QA scripts (independent of the builder's label code).

Never imports env.labels / env.labels_replay / monitors.prompts text. Discovery of worlds:
  1. case manifests under cases/ (any *.json / *.jsonl that has rows with a pid/db field) -- builder output
  2. spike runs: runs/*/private/world_index.json (+ deterministic_checks.json for the builder's label values)
  3. QA-local worlds generated by qa/gen_qa_worlds.py into the QA scratch dir (labelled source="qa_local")
"""
