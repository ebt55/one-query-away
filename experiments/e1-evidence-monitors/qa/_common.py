QA_OUT.mkdir(exist_ok=True)
QA_LOCAL = Path(os.environ.get("QA_LOCAL_DIR", str(QA / "_local_worlds")))


def sha256_text(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def sha256_obj(o) -> str:
    return sha256_text(json.dumps(o, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str))


def file_sha(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def tables(conn) -> set[str]:
    return {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}


def rows(conn, t: str) -> list[dict]:
    cur = conn.execute(f"SELECT * FROM {t}")
    cols = [d[0] for d in cur.description]
    return [dict(zip(cols, r)) for r in cur.fetchall()]


def open_ro(db: Path):
    return sqlite3.connect(f"file:{Path(db).as_posix()}?mode=ro", uri=True)


